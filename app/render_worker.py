"""In-process CadQuery render worker for the frozen desktop sidecar (ADR 0010 Phase 1b).

A PyInstaller-frozen ``promptcad-sidecar.exe`` has no separate ``python.exe`` that could run
a job's generated ``model.py``. :class:`app.services.renderer.Renderer` therefore re-invokes
the sidecar executable itself::

    promptcad-sidecar --render-worker <abs model.py> --output-dir <abs job dir> --formats step stl

``app.sidecar`` dispatches here before importing uvicorn/FastAPI. The worker checks its
arguments and executes ``model.py`` as ``__main__`` with the bundled CadQuery runtime.

Exit codes: ``0`` success, ``1`` the model failed (traceback on stderr), ``2`` usage error or
path rejection.

The path checks are defence in depth against argument confusion (a stray or attacker-chosen
path being run with the bundled interpreter); they are *not* a sandbox. ``model.py`` is
generated by PromptCAD's own compiler and runs with the sidecar's full privileges.

Only the standard library is imported here so the worker starts quickly.
"""

from __future__ import annotations

import argparse
import os
import runpy
import sys
import traceback
from collections.abc import Sequence
from pathlib import Path

RENDER_ROOT_ENV = "PROMPTCAD_RENDER_ROOT"
MODEL_FILENAME = "model.py"
FORMATS = ("step", "stl", "dxf", "svg")

EXIT_OK = 0
EXIT_MODEL_FAILED = 1
EXIT_USAGE = 2


class _Rejected(Exception):
    """An argument failed a path check."""


def _parse_args(argv: Sequence[str]) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        prog="promptcad-sidecar --render-worker",
        description="Run a generated PromptCAD model.py with the bundled CadQuery runtime",
    )
    parser.add_argument("model", help="absolute path to the job's model.py")
    parser.add_argument("--output-dir", required=True, help="absolute path to the job directory")
    parser.add_argument("--formats", nargs="*", default=[], choices=FORMATS)
    return parser.parse_args(list(argv))


def _resolve_existing(raw: str, what: str) -> Path:
    path = Path(raw)
    if not path.is_absolute():
        raise _Rejected(f"{what} must be an absolute path: {raw!r}")
    try:
        return path.resolve(strict=True)
    except (OSError, RuntimeError) as exc:
        raise _Rejected(f"{what} does not exist: {raw!r} ({exc})") from exc


def _check_paths(model_arg: str, output_dir_arg: str) -> tuple[Path, Path]:
    root_value = os.environ.get(RENDER_ROOT_ENV, "").strip()
    if not root_value:
        raise _Rejected(f"{RENDER_ROOT_ENV} is not set")
    root = _resolve_existing(root_value, RENDER_ROOT_ENV)
    if not root.is_dir():
        raise _Rejected(f"{RENDER_ROOT_ENV} is not a directory: {root_value!r}")

    model = _resolve_existing(model_arg, "model")
    if model.name != MODEL_FILENAME or not model.is_file():
        raise _Rejected(f"model must be a file named {MODEL_FILENAME}: {model_arg!r}")

    output_dir = _resolve_existing(output_dir_arg, "--output-dir")
    if output_dir != model.parent:
        raise _Rejected("--output-dir must be the directory that contains model.py")
    if root not in output_dir.parents:
        raise _Rejected(f"the job directory must be strictly inside {RENDER_ROOT_ENV}")
    return model, output_dir


def _exit_code(exc: SystemExit) -> int:
    code = exc.code
    if code is None or code == 0:
        return EXIT_OK
    if not isinstance(code, int):
        # Mirror the interpreter: a non-integer exit argument is printed to stderr.
        print(code, file=sys.stderr)
    return EXIT_MODEL_FAILED


def main(argv: Sequence[str] | None = None) -> int:
    """Run the worker. ``argv`` excludes the leading ``--render-worker`` flag."""
    try:
        args = _parse_args(sys.argv[1:] if argv is None else argv)
    except SystemExit as exc:  # argparse: --help exits 0, errors exit 2
        return EXIT_OK if exc.code in (None, 0) else EXIT_USAGE

    try:
        model, output_dir = _check_paths(args.model, args.output_dir)
    except _Rejected as exc:
        print(f"promptcad-sidecar --render-worker: rejected: {exc}", file=sys.stderr)
        return EXIT_USAGE

    saved_argv = sys.argv
    sys.argv = [str(model), "--output-dir", str(output_dir), "--formats", *args.formats]
    try:
        runpy.run_path(str(model), run_name="__main__")
    except SystemExit as exc:
        return _exit_code(exc)
    except Exception:
        traceback.print_exc(file=sys.stderr)
        return EXIT_MODEL_FAILED
    finally:
        sys.argv = saved_argv
    return EXIT_OK


if __name__ == "__main__":
    raise SystemExit(main())
