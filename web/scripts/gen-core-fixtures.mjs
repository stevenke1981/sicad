// Regenerates src/test/fixtures/core-fixtures.ts by piping real requests into the real
// `promptcad-core rpc` binary. Not run by CI (the output is committed, and `tsc` checks it
// against the generated types). Build the binary first:
//   cargo build --release --locked --bins   (in crates/promptcad-core)
import { spawnSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '../..');
const exe = ['promptcad-core.exe', 'promptcad-core']
  .map((n) => resolve(root, 'crates/promptcad-core/target/release', n))
  .find(existsSync);
if (!exe) throw new Error('promptcad-core binary not found; build it first');

const rpc = (request) => {
  const out = spawnSync(exe, ['rpc'], { input: JSON.stringify(request), encoding: 'utf8' });
  if (out.status !== 0) throw new Error(`rpc failed: ${out.stderr}`);
  return JSON.parse(out.stdout);
};
const example = (name) => {
  const doc = JSON.parse(readFileSync(resolve(root, `examples/cad2/${name}.cad2.json`), 'utf8'));
  delete doc.expected_resolved; // example-only key, not part of the schema
  return doc;
};

const plate = example('plate-four-holes');
const box = example('enclosure-with-lid');
// Not a tree: p_body listed twice, a_sub a child of two assemblies → `repeated` tree nodes.
const repeated = {
  ...box,
  assemblies: [
    { id: 'a_main', name: '電子外殼', children: ['p_body', 'p_body', 'a_sub'] },
    { id: 'a_sub', name: '上蓋組', children: ['p_lid'] },
    { id: 'a_other', name: '備品', children: ['a_sub'] },
  ],
};
const entries = {
  plateDescribe: ['CoreResponse', rpc({ op: 'describe', document: plate })],
  enclosureDescribe: ['CoreResponse', rpc({ op: 'describe', document: box })],
  repeatedDescribe: ['CoreResponse', rpc({ op: 'describe', document: repeated })],
  plateValidate: ['CoreResponse', rpc({ op: 'validate', document: plate })],
  unsupportedVersionError: [
    'CoreResponse',
    rpc({ op: 'validate', document: { schema_version: '3.0' } }),
  ],
  versionResponse: ['CoreResponse', rpc({ op: 'version' })],
};

let ts = [
  '/* eslint-disable */',
  '// GENERATED by scripts/gen-core-fixtures.mjs from the real `promptcad-core rpc` binary',
  '// (see README.md). `satisfies` makes tsc check every fixture against the generated types.',
  "import type { CoreResponse } from '../../api/generated/core-response';",
  '',
].join('\n');
for (const [name, [type, value]] of Object.entries(entries)) {
  ts += `\nexport const ${name} = ${JSON.stringify(value, null, 2)} satisfies ${type};\n`;
}
writeFileSync(resolve(root, 'web/src/test/fixtures/core-fixtures.ts'), ts, 'utf8');
console.log('wrote core-fixtures.ts');
