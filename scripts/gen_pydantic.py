"""Generate Pydantic v2 models from the Rust core's JSON Schemas (ADR 0008).

Usage:
    python scripts/gen_pydantic.py            # (re)write app/models/generated/*.py
    python scripts/gen_pydantic.py --check    # exit 1 if a generated file has drifted

Requires the ``schema`` extra (``pip install -e ".[schema]"``), which pins
datamodel-code-generator exactly. Output is deterministic: no timestamp, built-in
formatter only (no black/isort version dependence), LF line endings.

schemars exports a Rust unit-variant enum with doc comments as
``oneOf: [{const, type: string, description}, ...]``, which the generator turns into
Literal unions. ``normalize_schema`` collapses those into ``{type: string, enum: [...]}``
first so Severity/Role/Layer become real ``StrEnum`` classes (same idea as
stripRefSiblings in web/scripts/gen-types.mjs). ``$ref`` siblings (``default``,
``description``) next to a ``$ref`` are kept; the generator handles them.
"""

from __future__ import annotations

import argparse
import copy
import json
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
SCHEMA_DIR = ROOT / "schemas" / "cad2"
OUT_DIR = ROOT / "app" / "models" / "generated"

# (schema file stem, output module)
TARGETS: tuple[tuple[str, str], ...] = (
    ("validation-report", "validation_report"),
    ("cad-document-2", "cad_document_2"),
)

INIT_CONTENT = (
    '"""Pydantic models generated from the Rust core JSON Schemas.\n\n'
    "Do not edit; run ``python scripts/gen_pydantic.py`` (ADR 0008).\n"
    '"""\n'
)

HEADER = (
    "# This file is generated by scripts/gen_pydantic.py from "
    "schemas/cad2/{schema}.schema.json.\n"
    "# DO NOT EDIT BY HAND; run `python scripts/gen_pydantic.py` (ADR 0008).\n"
)

GENERATOR_ARGS = [
    "--input-file-type", "jsonschema",
    "--output-model-type", "pydantic_v2.BaseModel",
    "--target-python-version", "3.11",
    "--formatters", "builtin",
    "--use-standard-collections",
    "--use-union-operator",
    "--use-subclass-enum",
    "--enum-field-as-literal", "none",
    "--disable-timestamp",
    "--field-constraints",
    "--use-annotated",
    "--disable-future-imports",
    "--strict-nullable",
    "--set-default-enum-member",
]  # fmt: skip


def _collapse_enums(node: Any) -> Any:
    """Recursively turn string ``oneOf`` const unions into ``{type, enum}``."""
    if isinstance(node, list):
        return [_collapse_enums(item) for item in node]
    if not isinstance(node, dict):
        return node
    one_of = node.get("oneOf")
    if (
        isinstance(one_of, list)
        and one_of
        and all(
            isinstance(v, dict) and v.get("type") == "string" and isinstance(v.get("const"), str)
            for v in one_of
        )
    ):
        out = {k: _collapse_enums(v) for k, v in node.items() if k != "oneOf"}
        out["type"] = "string"
        out["enum"] = [v["const"] for v in one_of]
        return out
    return {k: _collapse_enums(v) for k, v in node.items()}


def normalize_schema(schema: dict) -> dict:
    return _collapse_enums(copy.deepcopy(schema))


def generate(stem: str, module: str) -> bytes:
    schema = json.loads((SCHEMA_DIR / f"{stem}.schema.json").read_text(encoding="utf-8"))
    normalized = normalize_schema(schema)
    with tempfile.TemporaryDirectory() as tmp:
        src = Path(tmp) / f"{stem}.json"
        out = Path(tmp) / f"{module}.py"
        src.write_text(json.dumps(normalized, indent=2, sort_keys=True), encoding="utf-8")
        cmd = [
            sys.executable,
            "-m",
            "datamodel_code_generator",
            "--input",
            str(src),
            "--output",
            str(out),
            *GENERATOR_ARGS,
        ]
        proc = subprocess.run(cmd, capture_output=True, text=True, check=False, cwd=tmp)
        if proc.returncode != 0:
            raise RuntimeError(f"datamodel-codegen failed:\n{proc.stdout}\n{proc.stderr}")
        body = out.read_bytes().decode("utf-8")
    # The tool writes its own "generated by ... filename: <temp>" banner; replace it.
    lines = body.replace("\r\n", "\n").split("\n")
    while lines and lines[0].startswith("#"):
        lines.pop(0)
    text = HEADER.format(schema=stem) + "\n".join(lines).lstrip("\n")
    if not text.endswith("\n"):
        text += "\n"
    return text.encode("utf-8")


def outputs() -> dict[Path, bytes]:
    result = {OUT_DIR / "__init__.py": INIT_CONTENT.encode("utf-8")}
    for stem, module in TARGETS:
        result[OUT_DIR / f"{module}.py"] = generate(stem, module)
    return result


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if files are out of date")
    args = parser.parse_args(argv)

    files = outputs()
    if args.check:
        stale = [p for p, data in files.items() if not p.exists() or p.read_bytes() != data]
        if stale:
            for path in stale:
                print(f"{path} is out of date; run `python scripts/gen_pydantic.py`.", file=sys.stderr)
            return 1
        print("Generated Pydantic models are up to date.")
        return 0

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for path, data in files.items():
        path.write_bytes(data)
        print(f"Wrote {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
