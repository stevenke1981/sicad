def build_manifest(
    *,
    platform: str,
    machine: str,
    stats: tuple[int, int, int],
    pruned: bool,
    max_mib: float | None,
    prune: PruneResult | None,
    pruned_dists: Iterable[str],
    before_bytes: int | None = None,
) -> dict[str, Any]:
    """``build/sidecar/bundle-manifest.json`` (schema 1). Pure.

    Keys: ``platform`` (sys.platform), ``total_bytes`` (dereferenced onedir), ``kept_native``
    / ``removed_native`` (VTK extension modules and VTK-named libraries, onedir-relative
    POSIX paths), ``external_system_libs`` (libraries the target system must provide;
    always empty on Windows), ``pruned_dists`` (dists verified absent), plus bookkeeping.
    """
    total, files, links = stats
    return {
        "schema": MANIFEST_SCHEMA,
        "platform": platform,
        "machine": machine,
        "total_bytes": total,
        "total_mib": round(total / 1_048_576, 1),
        "before_prune_bytes": before_bytes,
        "files": files,
        "symlinks": links,
        "pruned": pruned,
        "max_mib": max_mib,
        "vtk_keep_modules": prune.keep_modules if prune else [],
        "kept_native": prune.kept_native if prune else [],
        "removed_native": prune.removed_native if prune else [],
        "unresolved_native": prune.unresolved if prune else [],
        "external_system_libs": prune.external_system_libs if prune else [],
        "pruned_dists": sorted(pruned_dists),
    }


def effective_max_mib(
    requested: float | None, *, no_prune: bool, platform: str = sys.platform
) -> float | None:
    """The size gate: explicit ``--max-mib`` (0 disables), else the platform default
    unless pruning is off. Pure."""
    if requested is not None:
        return requested or None
    if no_prune:
        return None
    return DEFAULT_MAX_MIB.get(platform)


# --------------------------------------------------------------------------- main


def _cadquery_importable() -> bool:
    try:
        return importlib.util.find_spec("cadquery") is not None
    except (ImportError, ValueError):
        return False


def _print_lines(lines: Iterable[str]) -> None:
    for line in lines:
        print(line)


def _slim(onedir: Path, exe: Path) -> PruneResult:
    shim = bundled_vtk_is_shim(exe)
    if shim is False:
        raise BuildError("the bundle's vtk module is the vtk wheel's vtk.py, not the slim shim")
    started = time.monotonic()
    keep = compute_keep_set()
    print(f"VTK keep-set: {len(keep)} vtkmodules entries ({time.monotonic() - started:.0f} s)")
    started = time.monotonic()
    result = prune_bundle(onedir, keep, exe=exe)
    print(
        f"Pruned {len(result.removed_native)} VTK files ({result.removed_bytes / 1_048_576:.1f}"
        f" MiB), kept {len(result.kept_native)} ({time.monotonic() - started:.0f} s)"
    )
    if result.external_system_libs:
        print("External system libraries: " + ", ".join(result.external_system_libs))
    return result


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Build the PromptCAD desktop sidecar (onedir)")
    parser.add_argument(
        "--no-cad",
        action="store_true",
        help="build without CadQuery (source-only sidecar); otherwise cadquery must be importable",
    )
    parser.add_argument(
        "--no-prune",
        action="store_true",
        help="skip the VTK slim (escape hatch: keeps every vtkmodules extension and library)",
    )
    parser.add_argument(
        "--max-mib",
        type=float,
        default=None,
        help="fail when the onedir exceeds this many MiB (default: 460 on Windows, none "
        "elsewhere or with --no-prune; 0 disables)",
    )
    args = parser.parse_args(argv)

    try:
        import PyInstaller.__main__ as pyinstaller
    except ImportError:
        print(
            "PyInstaller is missing: run `python scripts/desktop_env.py` and build with "
            ".venv-desktop's python",
            file=sys.stderr,
        )
        return 2
    if not args.no_cad and not _cadquery_importable():
        print(
            "cadquery is not importable from this interpreter "
            f"({sys.executable}).\nRun `python scripts/desktop_env.py` and build with "
            ".venv-desktop's python, or pass --no-cad for a source-only sidecar.",
            file=sys.stderr,
        )
        return 2
    include_cad = not args.no_cad
    prune = include_cad and not args.no_prune
    max_mib = effective_max_mib(args.max_mib, no_prune=args.no_prune)

    for path in clean_stale_outputs():
        print(f"Removed stale {path}", flush=True)

    BUILD_DIR.mkdir(parents=True, exist_ok=True)
    entry = BUILD_DIR / "promptcad_sidecar_entry.py"
    entry.write_text(ENTRY_SOURCE, encoding="utf-8", newline="\n")
    shim_dir = None
    if include_cad:
        write_vtk_shim(SHIM_DIR)
        shim_dir = SHIM_DIR

    started = time.monotonic()
    pyinstaller.run(pyinstaller_args(entry, include_cad=include_cad, shim_dir=shim_dir))
    elapsed = time.monotonic() - started

    exe = output_exe()
    onedir = onedir_path()
    if not exe.is_file() or not (onedir / "_internal").is_dir():
        print(f"PyInstaller did not produce {exe} + _internal/", file=sys.stderr)
        return 1
    print(f"Built {exe} in {elapsed:.0f} s")
    _print_lines(size_summary(onedir))
    before_bytes = tree_stats(onedir)[0]

    try:
        result = _slim(onedir, exe) if prune else None
        if result is not None:
            _print_lines(size_summary(onedir))
        bundled = bundle_top_levels(onedir, exe)
        absent, present = split_pruned_dists(
            PRUNED_DISTS, _installed_records(PRUNED_DISTS), bundled
        )
    except (BuildError, OSError, subprocess.TimeoutExpired) as exc:
        print(f"Slim step failed: {exc}", file=sys.stderr)
        return 1

    stats = tree_stats(onedir)
    manifest = build_manifest(
        platform=sys.platform,
        machine=platform_mod.machine(),
        stats=stats,
        pruned=result is not None,
        max_mib=max_mib,
        prune=result,
        pruned_dists=absent,
        before_bytes=before_bytes,
    )
    MANIFEST_PATH.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    print(f"Wrote {MANIFEST_PATH} ({stats[0] / 1_048_576:.1f} MiB, {stats[1]} files)")
    if present:
        rows = ", ".join(f"{d} ({'/'.join(m)})" for d, m in sorted(present.items()))
        print(f"PRUNED_DISTS found in the bundle: {rows}", file=sys.stderr)
        return 1

    smoke = subprocess.run([str(exe), "--help"], capture_output=True, text=True, timeout=120)
    if smoke.returncode != 0:
        print(f"Smoke test failed:\n{smoke.stdout}\n{smoke.stderr}", file=sys.stderr)
        return 1
    print("`--help` smoke OK; run scripts/frozen_smoke.py for the CadQuery render gate")
    if max_mib is not None and stats[0] > max_mib * 1_048_576:
        print(
            f"Onedir is {stats[0] / 1_048_576:.1f} MiB, over the {max_mib:g} MiB limit",
            file=sys.stderr,
        )
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
