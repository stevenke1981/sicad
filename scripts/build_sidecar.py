"""Freeze the FastAPI sidecar + CadQuery runtime for the Tauri shell (ADR 0002, ADR 0010 1b).

Usage - run with the desktop build venv (``python scripts/desktop_env.py`` creates it)::

    .venv-desktop/Scripts/python.exe scripts/build_sidecar.py [--no-cad]

Output is a PyInstaller **onedir** bundle at the layout contract the Rust shell expects::

    src-tauri/binaries/promptcad-sidecar/promptcad-sidecar.exe
    src-tauri/binaries/promptcad-sidecar/_internal/...

``tauri.conf.json`` ships that directory as a bundle resource (installed as
``<resource_dir>/sidecar/``). Onefile was rejected: it would extract ~800 MB to %TEMP% on
every launch, leak ``_MEI*`` dirs when the shell kills the job object, and re-extract for
every render worker.

The executable accepts the same arguments as ``python -m app.sidecar`` (server mode,
``--host 127.0.0.1 --port 0``) plus ``--render-worker <model.py> --output-dir <dir>
--formats ...`` (see :mod:`app.render_worker`), which the frozen renderer uses to run a
job's generated ``model.py`` with the bundled CadQuery.

The build refuses to run when ``cadquery`` is not importable, unless ``--no-cad`` is given
(then CadQuery is excluded and the sidecar falls back to source-only output).
"""

from __future__ import annotations

import argparse
import importlib.util
import os
import shutil
import subprocess
import sys
import time
from collections.abc import Iterable
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BUILD_DIR = ROOT / "build" / "sidecar"
BINARIES_DIR = ROOT / "src-tauri" / "binaries"
NAME = "promptcad-sidecar"
EXE_SUFFIX = ".exe" if sys.platform == "win32" else ""

ENTRY_SOURCE = """\
# Generated by scripts/build_sidecar.py - PyInstaller entry for the desktop sidecar.
from app.sidecar import main

if __name__ == "__main__":
    raise SystemExit(main())
"""

HIDDEN_IMPORTS = (
    "app.main",
    "app.sidecar",
    "app.render_worker",
    "uvicorn.lifespan.on",
    "uvicorn.loops.auto",
    "uvicorn.loops.asyncio",
    "uvicorn.protocols.http.auto",
    "uvicorn.protocols.http.h11_impl",
    "uvicorn.protocols.http.httptools_impl",
    "uvicorn.protocols.websockets.auto",
    "uvicorn.logging",
)

# Nothing in the app imports cadquery statically: the generated model.py does, at render
# time, through app.render_worker. Name it explicitly so PyInstaller follows it.
CAD_HIDDEN_IMPORTS = ("cadquery",)

# Size levers (ADR 0010 Phase 1b). cadquery's real import graph for a generated model.py is
# OCP, vtk/vtkmodules, casadi, nlopt, ezdxf, numpy, multimethod, pyparsing - keep those.
# These are only reachable through optional/dev paths and would add hundreds of MB.
PRUNED_MODULES = (
    "scipy",
    "llvmlite",
    "numba",
    "matplotlib",
    "IPython",
    "PIL",
    "PyQt5",
    "PySide6",
    "tkinter",
    "pytest",
)

# Data directories shipped inside the bundle (source dir relative to ROOT -> bundle dir).
# None today: the desktop UI is served from Tauri's own assets, so app/web_dist is
# deliberately NOT bundled (it would freeze whatever stale build happened to exist) and the
# frozen sidecar's "/" is the "frontend not built" stub. The legacy app/static UI is gone.
DATA_DIRS: tuple[tuple[str, str], ...] = ()

# Outputs of earlier layouts that must not be picked up by tauri-build or the shell.
STALE_OUTPUTS = (
    "promptcad-sidecar-x86_64-pc-windows-msvc.exe",  # Phase 1 onefile externalBin
    NAME,  # previous onedir build (or the debug placeholder from build.rs)
)


def onedir_path(binaries_dir: Path = BINARIES_DIR) -> Path:
    """The onedir bundle directory (layout contract with src-tauri)."""
    return binaries_dir / NAME


def output_exe(binaries_dir: Path = BINARIES_DIR) -> Path:
    return onedir_path(binaries_dir) / f"{NAME}{EXE_SUFFIX}"


def pyinstaller_args(
    entry: Path,
    *,
    include_cad: bool = True,
    dist_dir: Path = BINARIES_DIR,
    build_dir: Path = BUILD_DIR,
    root: Path = ROOT,
) -> list[str]:
    """PyInstaller CLI arguments. Pure: inspects nothing but ``root``'s data dirs."""
    sep = os.pathsep  # PyInstaller --add-data separator
    args = [
        str(entry),
        "--onedir",
        "--console",  # stdout carries the READY line; Tauri/the renderer spawn without a window
        "--noconfirm",
        "--clean",
        "--noupx",
        "--name",
        NAME,
        "--distpath",
        str(dist_dir),
        "--workpath",
        str(build_dir / "work"),
        "--specpath",
        str(build_dir),
        "--paths",
        str(root),
        "--collect-submodules",
        "app",
    ]
    hidden = HIDDEN_IMPORTS + (CAD_HIDDEN_IMPORTS if include_cad else ())
    for module in hidden:
        args += ["--hidden-import", module]
    excluded = PRUNED_MODULES + (() if include_cad else ("cadquery", "OCP"))
    for module in excluded:
        args += ["--exclude-module", module]
    for source, dest in DATA_DIRS:
        src = root / source
        if src.is_dir() and any(src.iterdir()):
            args += ["--add-data", f"{src}{sep}{dest}"]
    return args


def clean_stale_outputs(binaries_dir: Path = BINARIES_DIR) -> list[Path]:
    """Delete outputs of earlier builds/layouts; returns what was removed."""
    removed: list[Path] = []
    for name in STALE_OUTPUTS:
        path = binaries_dir / name
        if path.is_dir():
            shutil.rmtree(path)
        elif path.exists():
            path.unlink()
        else:
            continue
        removed.append(path)
    return removed


def _dir_stats(path: Path) -> tuple[int, int]:
    total = count = 0
    for item in path.rglob("*"):
        if item.is_file():
            total += item.stat().st_size
            count += 1
    return total, count


def size_summary(onedir: Path, top: int = 10) -> list[str]:
    total, count = _dir_stats(onedir)
    lines = [f"{onedir}: {total / 1_048_576:.1f} MiB in {count} files"]
    internal = onedir / "_internal"
    entries: list[tuple[int, str]] = []
    if internal.is_dir():
        for child in internal.iterdir():
            size = _dir_stats(child)[0] if child.is_dir() else child.stat().st_size
            entries.append((size, child.name + ("/" if child.is_dir() else "")))
    for size, name in sorted(entries, reverse=True)[:top]:
        lines.append(f"  {size / 1_048_576:8.1f} MiB  _internal/{name}")
    return lines


def _cadquery_importable() -> bool:
    try:
        return importlib.util.find_spec("cadquery") is not None
    except (ImportError, ValueError):
        return False


def _print_lines(lines: Iterable[str]) -> None:
    for line in lines:
        print(line)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Build the PromptCAD desktop sidecar (onedir)")
    parser.add_argument(
        "--no-cad",
        action="store_true",
        help="build without CadQuery (source-only sidecar); otherwise cadquery must be importable",
    )
    args = parser.parse_args(argv)

    try:
        import PyInstaller.__main__ as pyinstaller
    except ImportError:
        print(
            "PyInstaller is missing: run `python scripts/desktop_env.py` and build with "
            ".venv-desktop's python",
            file=sys.stderr,
        )
        return 2
    if not args.no_cad and not _cadquery_importable():
        print(
            "cadquery is not importable from this interpreter "
            f"({sys.executable}).\nRun `python scripts/desktop_env.py` and build with "
            ".venv-desktop's python, or pass --no-cad for a source-only sidecar.",
            file=sys.stderr,
        )
        return 2

    for path in clean_stale_outputs():
        print(f"Removed stale {path}", flush=True)

    BUILD_DIR.mkdir(parents=True, exist_ok=True)
    entry = BUILD_DIR / "promptcad_sidecar_entry.py"
    entry.write_text(ENTRY_SOURCE, encoding="utf-8", newline="\n")

    started = time.monotonic()
    pyinstaller.run(pyinstaller_args(entry, include_cad=not args.no_cad))
    elapsed = time.monotonic() - started

    exe = output_exe()
    if not exe.is_file() or not (onedir_path() / "_internal").is_dir():
        print(f"PyInstaller did not produce {exe} + _internal/", file=sys.stderr)
        return 1
    print(f"Built {exe} in {elapsed:.0f} s")
    _print_lines(size_summary(onedir_path()))

    smoke = subprocess.run([str(exe), "--help"], capture_output=True, text=True, timeout=120)
    if smoke.returncode != 0:
        print(f"Smoke test failed:\n{smoke.stdout}\n{smoke.stderr}", file=sys.stderr)
        return 1
    print("`--help` smoke OK; run scripts/frozen_smoke.py for the CadQuery render gate")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
