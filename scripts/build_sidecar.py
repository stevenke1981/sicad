def pyinstaller_args(
    entry: Path,
    *,
    include_cad: bool = True,
    dist_dir: Path = BINARIES_DIR,
    build_dir: Path = BUILD_DIR,
    root: Path = ROOT,
    shim_dir: Path | None = None,
) -> list[str]:
    """PyInstaller CLI arguments. Pure: inspects nothing but ``root``'s data dirs.

    ``shim_dir`` (holding the slim ``vtk.py``) is searched before ``root`` and
    site-packages, so the bundle's ``vtk`` is the shim.
    """
    sep = os.pathsep  # PyInstaller --add-data separator
    args = [
        str(entry),
        "--onedir",
        "--console",  # stdout carries the READY line; Tauri/the renderer spawn without a window
        "--noconfirm",
        "--clean",
        "--noupx",
        "--name",
        NAME,
        "--distpath",
        str(dist_dir),
        "--workpath",
        str(build_dir / "work"),
        "--specpath",
        str(build_dir),
    ]
    if shim_dir is not None and include_cad:
        args += ["--paths", str(shim_dir)]
    args += ["--paths", str(root), "--collect-submodules", "app"]
    hidden = HIDDEN_IMPORTS + (CAD_HIDDEN_IMPORTS if include_cad else ())
    for module in hidden:
        args += ["--hidden-import", module]
    excluded = PRUNED_MODULES + (() if include_cad else ("cadquery", "OCP"))
    for module in excluded:
        args += ["--exclude-module", module]
    for source, dest in DATA_DIRS:
        src = root / source
        if src.is_dir() and any(src.iterdir()):
            args += ["--add-data", f"{src}{sep}{dest}"]
    return args


def clean_stale_outputs(binaries_dir: Path = BINARIES_DIR) -> list[Path]:
    """Delete outputs of earlier builds/layouts; returns what was removed."""
    removed: list[Path] = []
    for name in STALE_OUTPUTS:
        path = binaries_dir / name
        if path.is_dir() and not path.is_symlink():
            shutil.rmtree(path)
        elif path.exists() or path.is_symlink():
            path.unlink()
        else:
            continue
        removed.append(path)
    return removed


# --------------------------------------------------------------------------- sizes


def walk_files(path: Path) -> list[Path]:
    """Every file and symlink under ``path`` (symlinked directories are not descended)."""
    found: list[Path] = []
    for dirpath, dirnames, filenames in os.walk(path, followlinks=False):
        base = Path(dirpath)
        found.extend(base / name for name in filenames)
        found.extend(base / name for name in dirnames if (base / name).is_symlink())
    return found


def tree_stats(path: Path) -> tuple[int, int, int]:
    """(dereferenced bytes, files, symlinks) of a directory tree.

    Symlinks count with their target's size (a symlinked directory with its whole tree):
    that is what a copy that dereferences links - e.g. a resource copy - ends up shipping.
    """
    total = files = links = 0
    for item in walk_files(path):
        if item.is_symlink():
            links += 1
            if item.is_dir():
                total += tree_stats(item.resolve())[0]
                continue
        if item.is_file():
            total += item.stat().st_size
            files += 1
    return total, files, links


def _dir_stats(path: Path) -> tuple[int, int]:
    total, files, _ = tree_stats(path)
    return total, files


def size_summary(onedir: Path, top: int = 10) -> list[str]:
    total, count = _dir_stats(onedir)
    lines = [f"{onedir}: {total / 1_048_576:.1f} MiB in {count} files"]
    internal = onedir / "_internal"
    entries: list[tuple[int, str]] = []
    if internal.is_dir():
        for child in internal.iterdir():
            size = _dir_stats(child)[0] if child.is_dir() else child.stat().st_size
            entries.append((size, child.name + ("/" if child.is_dir() else "")))
    for size, name in sorted(entries, reverse=True)[:top]:
        lines.append(f"  {size / 1_048_576:8.1f} MiB  _internal/{name}")
    return lines


# --------------------------------------------------------------------------- VTK prune


def vtk_extension_stem(name: str) -> str | None:
    """``vtkCommonCore`` for a vtkmodules extension module file name, else None. Pure."""
    match = _EXTENSION_RE.match(name)
    return match.group("stem") if match else None


def unused_vtk_extensions(files: Iterable[Path], keep_modules: Iterable[str]) -> list[Path]:
    """Extension modules (files directly in ``vtkmodules/``) not in the keep-set. Pure."""
    keep = set(keep_modules)
    unused = []
    for path in files:
        stem = vtk_extension_stem(path.name)
        if stem and f"vtkmodules.{stem}" not in keep:
            unused.append(path)
    return sorted(unused)


def is_vtk_native(name: str, kind: str) -> bool:
    """Whether a file name is a VTK-named shared library for binary format ``kind``. Pure."""
    return any(pattern.match(name) for pattern in VTK_NATIVE_PATTERNS[kind])


def _real(path: Path) -> Path:
    try:
        return path.resolve()
    except OSError:
        return path


def _rel(path: Path, onedir: Path) -> str:
    try:
        return path.relative_to(onedir).as_posix()
    except ValueError:
        return path.as_posix()


@dataclass
class PruneResult:
    """What :func:`prune_bundle` kept and deleted (paths relative to the onedir, POSIX)."""

    keep_modules: list[str]
    kept_native: list[str] = field(default_factory=list)
    removed_native: list[str] = field(default_factory=list)
    removed_bytes: int = 0
    unresolved: list[str] = field(default_factory=list)
    external_system_libs: list[str] = field(default_factory=list)


def prune_bundle(
    onedir: Path,
    keep_modules: Iterable[str],
    *,
    kind: str | None = None,
    exe: Path | None = None,
    deps_of: Callable[[Path], list[str]] | None = None,
    dry_run: bool = False,
) -> PruneResult:
    """Steps 2 and 3 of the slim (see the module docstring). Deletes files unless ``dry_run``.

    Raises :class:`BuildError` when a root's dependencies cannot be read: deleting on an
    incomplete closure could break the bundle.
    """
    kind = kind or native_deps.flavour()
    keep_modules = sorted(set(keep_modules))
    result = PruneResult(keep_modules=keep_modules)
    exe = exe or onedir / (NAME + (".exe" if kind == native_deps.PE else ""))

    vtkmodules = onedir / "_internal" / "vtkmodules"
    direct = [p for p in vtkmodules.iterdir() if p.is_file()] if vtkmodules.is_dir() else []
    doomed_ext = set(unused_vtk_extensions(direct, keep_modules))
    kept_ext = [p for p in direct if vtk_extension_stem(p.name) and p not in doomed_ext]

    files = [p for p in walk_files(onedir) if p not in doomed_ext]
    binaries = [p for p in files if native_deps.is_native_binary(p, kind)]
    vtk_named = [p for p in files if is_vtk_native(p.name, kind)]
    vtk_set = set(vtk_named)
    roots = [p for p in binaries if p not in vtk_set]
    if exe.is_file() and exe not in roots:
        roots.append(exe)
    index = native_deps.build_index(sorted(set(binaries) | vtk_set), kind)
    reach = native_deps.closure(roots, index, kind=kind, deps_of=deps_of)
    if reach.errors:
        rows = "\n".join(f"  {_rel(p, onedir)}: {e}" for p, e in sorted(reach.errors.items()))
        raise BuildError(f"cannot read native dependencies (use --no-prune to skip):\n{rows}")
    reached_real = {_real(p) for p in reach.reached}

    doomed_lib = [
        p for p in vtk_named if p not in reach.reached and _real(p) not in reached_real
    ]
    kept_lib = [p for p in vtk_named if p not in set(doomed_lib)]
    for path in sorted(doomed_ext) + sorted(doomed_lib):
        result.removed_native.append(_rel(path, onedir))
        if not path.is_symlink():
            result.removed_bytes += path.stat().st_size
        if not dry_run:
            path.unlink()
    result.kept_native = sorted(_rel(p, onedir) for p in kept_ext + kept_lib)
    result.unresolved = sorted(reach.unresolved)
    result.external_system_libs = native_deps.external_system_libs(reach.unresolved, kind)
    return result


def write_vtk_shim(shim_dir: Path = SHIM_DIR) -> Path:
    if shim_dir.exists():
        shutil.rmtree(shim_dir)
    shim_dir.mkdir(parents=True)
    path = shim_dir / "vtk.py"
    path.write_text(VTK_SHIM_SOURCE, encoding="utf-8", newline="\n")
    return path


def example_models(examples_dir: Path = EXAMPLES_DIR) -> list[Path]:
    return sorted(examples_dir.glob("*/model.py"))


def compute_keep_set(
    shim_dir: Path = SHIM_DIR,
    *,
    python: str = sys.executable,
    root: Path = ROOT,
    models: Iterable[Path] | None = None,
    timeout: float = 900,
) -> list[str]:
    """``vtkmodules.*`` modules a real render imports with the shim (build-venv subprocess)."""
    models = list(example_models() if models is None else models)
    if not models:
        raise BuildError(f"no example model.py under {EXAMPLES_DIR} to observe the keep-set")
    with tempfile.TemporaryDirectory(prefix="promptcad-keepset-out-") as tmp:
        out = Path(tmp) / "keep.json"
        completed = subprocess.run(
            [python, "-I", "-c", KEEPSET_SCRIPT, str(shim_dir), str(root), str(out)]
            + [str(m) for m in models],
            capture_output=True,
            text=True,
            timeout=timeout,
            check=False,
        )
        if completed.returncode != 0 or not out.is_file():
            raise BuildError(
                f"keep-set probe failed ({completed.returncode}):\n{completed.stderr[-4000:]}"
            )
        modules = json.loads(out.read_text(encoding="utf-8"))
    if "vtkmodules.vtkCommonCore" not in modules:
        raise BuildError(f"implausible keep-set (no vtkCommonCore): {modules}")
    return modules


# --------------------------------------------------------------------------- bundle contents


def _pyz_reader(exe: Path) -> Any:
    from PyInstaller.archive.readers import CArchiveReader  # build venv only

    archive = CArchiveReader(str(exe))
    for name, entry in archive.toc.items():
        if entry[-1] == "z":  # PYZ typecode
            return archive.open_embedded_archive(name)
    raise BuildError(f"no PYZ archive in {exe}")


def bundled_top_levels(
    pyz_names: Iterable[str], internal_names: Iterable[str], base_library: Iterable[str]
) -> set[str]:
    """Lower-cased top-level module/package names present in a bundle. Pure."""
    names = {n.split(".")[0] for n in pyz_names}
    names |= {n.split(".")[0] for n in internal_names}
    names |= {n.split("/")[0].split(".")[0] for n in base_library}
    return {n.lower() for n in names if n}


def dist_top_levels(record_paths: Iterable[str]) -> set[str]:
    """Lower-cased importable top-level names a dist installs, from its RECORD. Pure."""
    tops = set()
    for raw in record_paths:
        first = raw.replace("\\", "/").split("/")[0]
        if not first or first in ("..", "bin", "Scripts") or first.endswith((".dist-info", ".data")):
            continue
        if first.endswith(".pth"):
            continue
        tops.add(first.split(".")[0].lower())
    return tops


def split_pruned_dists(
    dists: Iterable[str], installed: Mapping[str, Iterable[str]], bundled: set[str]
) -> tuple[list[str], dict[str, list[str]]]:
    """(verified absent, {dist: top-level names found in the bundle}). Pure.

    A dist that is not installed at all counts as absent.
    """
    absent, present = [], {}
    for dist in dists:
        hits = sorted(dist_top_levels(installed.get(dist, ())) & bundled)
        if hits:
            present[dist] = hits
        else:
            absent.append(dist)
    return absent, present


def _installed_records(dists: Iterable[str]) -> dict[str, list[str]]:
    from importlib import metadata

    records: dict[str, list[str]] = {}
    for dist in dists:
        try:
            files = metadata.distribution(dist).files or []
        except metadata.PackageNotFoundError:
            continue
        records[dist] = [str(f) for f in files]
    return records


def bundle_top_levels(onedir: Path, exe: Path) -> set[str]:
    internal = onedir / "_internal"
    base_library: list[str] = []
    base_zip = internal / "base_library.zip"
    if base_zip.is_file():
        with zipfile.ZipFile(base_zip) as archive:
            base_library = archive.namelist()
    return bundled_top_levels(
        _pyz_reader(exe).toc.keys(),
        (p.name for p in internal.iterdir()) if internal.is_dir() else (),
        base_library,
    )


def bundled_vtk_is_shim(exe: Path) -> bool | None:
    """Whether the bundle's ``vtk`` module is the slim shim (None: no ``vtk`` at all)."""
    pyz = _pyz_reader(exe)
    if "vtk" not in pyz.toc:
        return None
    code = pyz.extract("vtk")
    return VTK_SHIM_MARKER in getattr(code, "co_names", ())


