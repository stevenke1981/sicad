"""Freeze the FastAPI sidecar into a single executable for the Tauri shell (ADR 0002).

Usage (requires the ``desktop`` extra: ``pip install -e ".[desktop]"``):

    python scripts/build_sidecar.py [--target x86_64-pc-windows-msvc]

Output: ``src-tauri/binaries/promptcad-sidecar-<target-triple>[.exe]`` - the name Tauri's
``externalBin: ["binaries/promptcad-sidecar"]`` expects. The binary accepts the same
arguments as ``python -m app.sidecar`` (``--host 127.0.0.1 --port 0``).

CadQuery is intentionally not bundled (deferred); the frozen sidecar reports
``cadquery_available: false`` and falls back to source-only output.
"""

from __future__ import annotations

import argparse
import os
import platform
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
APP_DIR = ROOT / "app"
BUILD_DIR = ROOT / "build" / "sidecar"
BINARIES_DIR = ROOT / "src-tauri" / "binaries"
NAME = "promptcad-sidecar"

ENTRY_SOURCE = """\
# Generated by scripts/build_sidecar.py - PyInstaller entry for the desktop sidecar.
from app.sidecar import main

if __name__ == "__main__":
    raise SystemExit(main())
"""

HIDDEN_IMPORTS = (
    "app.main",
    "app.sidecar",
    "uvicorn.lifespan.on",
    "uvicorn.loops.auto",
    "uvicorn.loops.asyncio",
    "uvicorn.protocols.http.auto",
    "uvicorn.protocols.http.h11_impl",
    "uvicorn.protocols.http.httptools_impl",
    "uvicorn.protocols.websockets.auto",
    "uvicorn.logging",
)

# Data directories shipped inside the bundle (source dir relative to ROOT -> bundle dir).
# app/web_dist is deliberately NOT bundled: the desktop UI is served from Tauri's own
# assets, and bundling it here would freeze whatever stale build happened to exist.
DATA_DIRS = (("app/static", "app/static"),)


def host_target_triple() -> str:
    machine = platform.machine().lower()
    arch = {"amd64": "x86_64", "x86_64": "x86_64", "arm64": "aarch64", "aarch64": "aarch64"}.get(
        machine, machine
    )
    if sys.platform == "win32":
        return f"{arch}-pc-windows-msvc"  # Tauri on Windows requires the MSVC toolchain
    if sys.platform == "darwin":
        return f"{arch}-apple-darwin"
    return f"{arch}-unknown-linux-gnu"


def pyinstaller_args(entry: Path, target: str) -> list[str]:
    sep = os.pathsep  # PyInstaller --add-data separator
    args = [
        str(entry),
        "--onefile",
        "--console",  # stdout carries the READY line; Tauri spawns without a window
        "--noconfirm",
        "--clean",
        "--name",
        f"{NAME}-{target}",
        "--distpath",
        str(BUILD_DIR / "dist"),
        "--workpath",
        str(BUILD_DIR / "work"),
        "--specpath",
        str(BUILD_DIR),
        "--paths",
        str(ROOT),
        "--collect-submodules",
        "app",
        "--exclude-module",
        "cadquery",
        "--exclude-module",
        "tkinter",
        "--exclude-module",
        "pytest",
    ]
    for module in HIDDEN_IMPORTS:
        args += ["--hidden-import", module]
    for source, dest in DATA_DIRS:
        src = ROOT / source
        if src.is_dir() and any(src.iterdir()):
            args += ["--add-data", f"{src}{sep}{dest}"]
    return args


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Build the PromptCAD desktop sidecar")
    parser.add_argument("--target", default=host_target_triple(), help="Rust target triple")
    args = parser.parse_args(argv)

    try:
        import PyInstaller.__main__ as pyinstaller
    except ImportError:
        print(
            'PyInstaller is missing: pip install -e ".[desktop]"',
            file=sys.stderr,
        )
        return 2

    BUILD_DIR.mkdir(parents=True, exist_ok=True)
    entry = BUILD_DIR / "promptcad_sidecar_entry.py"
    entry.write_text(ENTRY_SOURCE, encoding="utf-8", newline="\n")

    pyinstaller.run(pyinstaller_args(entry, args.target))

    suffix = ".exe" if "windows" in args.target else ""
    built = BUILD_DIR / "dist" / f"{NAME}-{args.target}{suffix}"
    if not built.is_file():
        print(f"PyInstaller did not produce {built}", file=sys.stderr)
        return 1
    BINARIES_DIR.mkdir(parents=True, exist_ok=True)
    final = BINARIES_DIR / built.name
    shutil.copy2(built, final)
    print(f"Built {final} ({final.stat().st_size / 1_048_576:.1f} MiB)")

    smoke = subprocess.run([str(final), "--help"], capture_output=True, text=True, timeout=120)
    if smoke.returncode != 0:
        print(f"Smoke test failed:\n{smoke.stdout}\n{smoke.stderr}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
