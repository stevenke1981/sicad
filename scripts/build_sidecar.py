"""Freeze the FastAPI sidecar + CadQuery runtime for the Tauri shell (ADR 0002, ADR 0010 1b).

Usage - run with the desktop build venv (``python scripts/desktop_env.py`` creates it)::

    .venv-desktop/Scripts/python.exe scripts/build_sidecar.py [--no-cad] [--no-prune]
        [--max-mib N]

Output is a PyInstaller **onedir** bundle at the layout contract the Rust shell expects::

    src-tauri/binaries/promptcad-sidecar/promptcad-sidecar[.exe]
    src-tauri/binaries/promptcad-sidecar/_internal/...

``tauri.conf.json`` ships that directory as a bundle resource (installed as
``<resource_dir>/sidecar/``). Onefile was rejected: it would extract ~800 MB to %TEMP% on
every launch, leak ``_MEI*`` dirs when the shell kills the job object, and re-extract for
every render worker.

The executable accepts the same arguments as ``python -m app.sidecar`` (server mode,
``--host 127.0.0.1 --port 0``) plus ``--render-worker <model.py> --output-dir <dir>
--formats ...`` (see :mod:`app.render_worker`), which the frozen renderer uses to run a
job's generated ``model.py`` with the bundled CadQuery.

The build refuses to run when ``cadquery`` is not importable, unless ``--no-cad`` is given
(then CadQuery is excluded and the sidecar falls back to source-only output).

Slimming (ADR 0011), after PyInstaller and unless ``--no-prune``:

1. keep-set - a build-venv subprocess runs the render worker on the checked-in example
   models (all four formats) with the slim ``vtk`` shim first on ``sys.path`` and records
   every ``vtkmodules.*`` entry of ``sys.modules``. The shim replaces the vtk wheel's
   ``vtk.py`` (``vtkmodules.all``) in the bundle: OCP's ``IVtk*`` wrappers ``import vtk``
   only to get VTK's libraries loaded, and with the real module the keep-set would be
   every VTK module;
2. ``vtkmodules`` extension modules outside the keep-set are deleted;
3. the native dependency closure (:mod:`native_deps`) of every remaining binary that is not
   itself VTK-named is computed, and VTK-named libraries (``vtk*-9*.dll``, ``libvtk*.so*``,
   ``libvtk*.dylib`` and the vtk wheel's ``viskores*`` libraries) outside it are deleted.
   Nothing else is ever deleted.

``build/sidecar/bundle-manifest.json`` records the result (:func:`build_manifest`). The
build fails when the dereferenced onedir exceeds ``--max-mib`` (Windows default 460; ``0``
disables; no default with ``--no-prune``) or when a dist of :data:`PRUNED_DISTS` turns up
in the bundle.
"""

