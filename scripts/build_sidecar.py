# ``import vtk`` makes OCP skip IVtkOCC and ``import cadquery`` fail, so the frozen smoke
# gate covers the shim.
VTK_SHIM_MARKER = "PROMPTCAD_VTK_SHIM"
VTK_SHIM_SOURCE = f'''\
"""Slim ``vtk`` for the PromptCAD sidecar bundle (generated by scripts/build_sidecar.py)."""

from vtkmodules.vtkCommonCore import *  # noqa: F403

{VTK_SHIM_MARKER} = True
'''

# Runs in the build venv (``python -I -c KEEPSET_SCRIPT shim root out model...``): renders
# every model with every format through app.render_worker, then dumps the vtkmodules.*
# entries of sys.modules to ``out`` (stdout belongs to the model).
KEEPSET_SCRIPT = f"""\
import json, os, shutil, sys, tempfile
shim, root, out, models = sys.argv[1], sys.argv[2], sys.argv[3], sys.argv[4:]
sys.path[:0] = [shim, root]
from app import render_worker
work = tempfile.mkdtemp(prefix="promptcad-keepset-")
os.environ["PROMPTCAD_RENDER_ROOT"] = work
try:
    for i, model in enumerate(models):
        job = os.path.join(work, "job-%d" % i)
        os.mkdir(job)
        shutil.copy2(model, os.path.join(job, "model.py"))
        code = render_worker.main([os.path.join(job, "model.py"), "--output-dir", job,
                                   "--formats", "step", "stl", "dxf", "svg"])
        if code != 0:
            raise SystemExit("keep-set render of %s exited %s" % (model, code))
        for name in ("model.step", "model.stl", "model.dxf", "model.svg"):
            path = os.path.join(job, name)
            if not os.path.isfile(path) or os.path.getsize(path) == 0:
                raise SystemExit("keep-set render of %s did not write %s" % (model, name))
    vtk = sys.modules.get("vtk")
    if vtk is not None and getattr(vtk, "{VTK_SHIM_MARKER}", False) is not True:
        raise SystemExit("import vtk resolved to %s, not the slim shim" % vtk.__file__)
    with open(out, "w", encoding="utf-8") as handle:
        json.dump(sorted(m for m in sys.modules if m.startswith("vtkmodules.")), handle)
finally:
    shutil.rmtree(work, ignore_errors=True)
"""

# VTK-named native libraries - the only files step 3 may delete. Matched on the file name
# wherever they live (vtk.libs/, vtkmodules/, vtkmodules/.dylibs/, _internal/).
